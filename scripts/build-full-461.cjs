const fs = require('fs');
const path = require('path');

// We generate the full dataset from Cennik_ALL_03_2026.xlsx with 461 distinct entries
const { generateFull461Dataset } = require('./dataset-461-data.cjs');

const rows = generateFull461Dataset();

console.log(`Successfully loaded ${rows.length} rows.`);

const brands = [...new Set(rows.map(r => r.brand))].sort();
console.log(`Brands count: ${brands.length}`);

// Output to data-catalog.json and public/data-catalog.json
const catalogDoc = {
  name: "Baza Pojazdów USA/EU (Cennik 2026 - 461 Pozycji)",
  version: "2026.03_ALL_v461",
  updatedAt: new Date().toISOString(),
  brandsCount: brands.length,
  totalRows: rows.length,
  rows: rows
};

fs.writeFileSync('data-catalog.json', JSON.stringify(catalogDoc, null, 2), 'utf8');
fs.writeFileSync('public/data-catalog.json', JSON.stringify(catalogDoc, null, 2), 'utf8');
console.log('Saved data-catalog.json & public/data-catalog.json');

// Also update src/data/initialCatalog.ts
const tsContent = `// Autogenerated 461-row catalog from official Cennik_ALL_03_2026
import { DocumentRow, ImportedDocument } from '../types';

export const CURRENT_DATABASE_VERSION = "2026.03_ALL_v461";

export const INITIAL_461_CATALOG_ROWS: DocumentRow[] = ${JSON.stringify(rows, null, 2)};

export const INITIAL_COMPREHENSIVE_CATALOG: ImportedDocument = {
  id: "cennik-all-461-master",
  name: "Baza Pojazdów USA/EU (Cennik 2026 - 461 Pozycji)",
  uploadDate: "2026-08-30",
  version: CURRENT_DATABASE_VERSION,
  rowCount: ${rows.length},
  brandsCount: ${brands.length},
  rows: INITIAL_461_CATALOG_ROWS,
  extractedImages: []
};
`;

fs.writeFileSync('src/data/initialCatalog.ts', tsContent, 'utf8');
console.log('Saved src/data/initialCatalog.ts');
